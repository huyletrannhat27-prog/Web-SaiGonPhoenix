const request = require('supertest');
const mongoose = require('mongoose');
require('dotenv').config();
const app = require('../server');
const connectDB = require('../config/database');
const User = require('../models/User');
const Booking = require('../models/Booking');
const Vehicle = require('../models/Vehicle');
const ImageAsset = require('../models/ImageAsset');
const path = require('path');

(async () => {
    await connectDB();
    const testEmail = 'codex-test@saigonphoenix.local';
    await User.deleteOne({ email: testEmail });
    const home = await request(app).get('/');
    const guestBooking = await request(app).get('/booking');
    const admin = request.agent(app);
    const adminLogin = await admin.post('/login').type('form').send({ email: process.env.ADMIN_EMAIL || 'admin@saigonphoenix.com', password: process.env.ADMIN_PASSWORD || 'admin123' });
    const adminPage = await admin.get('/admin');
    const user = request.agent(app);
    const registered = await user.post('/register').type('form').send({ username: 'Khach Test', email: testEmail, phone: '0901234567', password: 'test123', confirmPassword: 'test123' });
    const loggedIn = await user.post('/login').type('form').send({ email: testEmail, password: 'test123' });
    const vehicle = await Vehicle.findOne({ isAvailable: true });
    const requestedBookingDate = new Date(Date.now() + 86400000).toISOString();
    const booked = await user.post('/booking').type('form').send({ vehicleId: vehicle._id.toString(), airport: 'Sân bay Tân Sơn Nhất (SGN)', tripType: 'airport-pickup', customerName: 'Khach Test', phone: '0901234567', bookingDate: requestedBookingDate, passengerCount: 2, luggageCount: 1, pickupLocation: 'Sân bay', dropoffLocation: 'Quận 1', paymentOption: 'deposit' });
    const testUser = await User.findOne({ email: testEmail });
    const savedBookings = await Booking.countDocuments({ user: testUser._id });
    const saved = await Booking.findOne({ user: testUser._id });
    const detail = await user.get(`/bookings/${saved._id}`);
    const paymentSubmitted = await user.post(`/bookings/${saved._id}/payment-submitted`);
    const availableAtSameTime = await user.get(`/api/vehicles?bookingDate=${encodeURIComponent(requestedBookingDate)}`);
    const unavailableIds = (await availableAtSameTime.body).map(item => String(item._id));
    const underpaid = await admin.post(`/admin/bookings/${saved._id}/payment`).type('form').send({ paidAmount: saved.payment.requiredAmount - 1 });
    const afterUnderpay = await Booking.findById(saved._id);
    const exactPayment = await admin.post(`/admin/bookings/${saved._id}/payment`).type('form').send({ paidAmount: saved.payment.requiredAmount });
    const afterExactPayment = await Booking.findById(saved._id);
    const deleteTarget = await Vehicle.create({ name: 'Codex Delete Test', type: '4 cho', price: 100000, capacity: 4 });
    const deleted = await admin.post(`/admin/vehicles/${deleteTarget._id}/delete`);
    const deletedVehicles = await Vehicle.countDocuments({ _id: deleteTarget._id });
    const uploadImage = await admin.post('/admin/images').attach('vehicleImage', path.join(__dirname, '..', 'README.md'), { filename: 'smoke-test.png', contentType: 'image/png' });
    const imageAsset = await ImageAsset.findOne({ originalName: 'smoke-test.png' });
    const createWithLibraryImage = await admin.post('/admin/vehicles').type('form').send({ name: 'Codex Image Test', type: '4 cho', price: 120000, capacity: 4, luggageCapacity: 2, imageAssetId: imageAsset._id.toString() });
    const imageVehicle = await Vehicle.findOne({ name: 'Codex Image Test' });
    const editPage = await admin.get(`/admin/vehicles/${imageVehicle._id}/edit`);
    const edited = await admin.post(`/admin/vehicles/${imageVehicle._id}/edit`).type('form').send({ name: 'Codex Edited Test', type: '7 cho', price: 220000, capacity: 7, luggageCapacity: 4, description: 'Edited', isAvailable: 'false' });
    const editedVehicle = await Vehicle.findById(imageVehicle._id);
    await admin.post(`/admin/vehicles/${imageVehicle._id}/delete`);
    const deleteImage = await admin.post(`/admin/images/${imageAsset._id}/delete`);
    const deletedImages = await ImageAsset.countDocuments({ _id: imageAsset._id });
    console.log({ home: home.status, guestBooking: guestBooking.status, adminLogin: adminLogin.status, adminPage: adminPage.status, registered: registered.status, loggedIn: loggedIn.status, booked: booked.status, savedBookings, depositAmount: saved.payment.requiredAmount, detail: detail.status, paymentSubmitted: paymentSubmitted.status, vehicleHiddenAtSameTime: !unavailableIds.includes(vehicle._id.toString()), underpayRejected: afterUnderpay.payment.status === 'pending_review', exactPaymentAccepted: afterExactPayment.payment.status === 'partial', deleteRoute: deleted.status, deletedVehicles, uploadImage: uploadImage.status, createWithLibraryImage: createWithLibraryImage.status, imageApplied: imageVehicle.images[0] === imageAsset.url, editPage: editPage.status, editRoute: edited.status, editApplied: editedVehicle.name === 'Codex Edited Test' && editedVehicle.price === 220000 && !editedVehicle.isAvailable, deleteImage: deleteImage.status, deletedImages });
    await Booking.deleteMany({ user: testUser._id });
    await User.deleteOne({ _id: testUser._id });
    await mongoose.disconnect();
    process.exit(0);
})().catch(async error => { console.error(error); await mongoose.disconnect(); process.exit(1); });
